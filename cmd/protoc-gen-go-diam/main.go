// protoc-gen-go-diam generates Diameter codecs from proto3 files annotated
// with the options in proto/diam/options.proto.
//
// For every message it emits a Go struct with AppendAVPs, DecodeAVPs and
// Validate. Messages marked (diam.command) also get Marshal, AppendMarshal,
// Unmarshal and a registration with the diam package. The generated code
// depends on github.com/hsdfat/go-diam/diam and the standard library only.
package main

import (
	"fmt"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/pluginpb"

	"github.com/hsdfat/go-diam/cmd/protoc-gen-go-diam/diampb"
)

// optionsPackage is the proto package of proto/diam/options.proto, which
// describes the schema language itself and gets no codec.
const optionsPackage = "diam"

func main() {
	protogen.Options{}.Run(run)
}

// run is the plugin body. Tests call it with an in-process request.
func run(gen *protogen.Plugin) error {
	gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
	d := newDict()
	for _, f := range gen.Files {
		d.collect(f)
	}
	for _, f := range gen.Files {
		if !f.Generate || f.Desc.Package() == optionsPackage {
			continue
		}
		if err := generateFile(gen, d, f); err != nil {
			return fmt.Errorf("%s: %w", f.Desc.Path(), err)
		}
	}
	return nil
}

func generateFile(gen *protogen.Plugin, d *dict, f *protogen.File) error {
	g := gen.NewGeneratedFile(f.GeneratedFilenamePrefix+".diam.go", f.GoImportPath)
	g.P("// Code generated by protoc-gen-go-diam. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()

	msgs := make([]*message, 0, len(f.Messages))
	for _, m := range f.Messages {
		msg, err := buildMessage(g, d, f, m)
		if err != nil {
			return err
		}
		msgs = append(msgs, msg)
	}

	for _, e := range f.Enums {
		if proto.GetExtension(e.Desc.Options(), diampb.E_Dictionary).(bool) {
			genDictConsts(g, e)
			continue
		}
		genEnum(g, e)
	}
	for _, msg := range msgs {
		genStruct(g, msg)
		genAppendAVPs(g, msg)
		genDecodeAVPs(g, msg)
		genValidate(g, msg)
		if msg.cmd != nil {
			genCommand(g, msg)
		}
	}
	genAnswerConstructors(g, msgs)
	genRegister(g, msgs)
	return nil
}
