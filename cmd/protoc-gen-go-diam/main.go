// protoc-gen-go-diam generates Diameter codecs from proto3 files annotated
// with the options in proto/diam/options.proto.
package main

import (
	"fmt"
	"sort"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"

	"github.com/hsdfat/go-diam/diampb"
)

const diamPkg = protogen.GoImportPath("github.com/hsdfat/go-diam/diam")

var (
	netipPkg = protogen.GoImportPath("net/netip")
	timePkg  = protogen.GoImportPath("time")
)

type avpDef struct {
	name   string // dictionary value name, e.g. ORIGIN_HOST
	code   uint32
	vendor uint32
	m      bool
	typ    diampb.Type
	file   string
}

type dict struct {
	byName map[string][]avpDef
}

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		d := &dict{byName: map[string][]avpDef{}}
		for _, f := range gen.Files {
			d.collect(f)
		}
		for _, f := range gen.Files {
			if !f.Generate || f.Desc.Package() == "diam" {
				continue
			}
			if err := generateFile(gen, d, f); err != nil {
				return fmt.Errorf("%s: %w", f.Desc.Path(), err)
			}
		}
		return nil
	})
}

func (d *dict) collect(f *protogen.File) {
	for _, e := range f.Enums {
		if !proto.GetExtension(e.Desc.Options(), diampb.E_Dictionary).(bool) {
			continue
		}
		for _, v := range e.Values {
			def, _ := proto.GetExtension(v.Desc.Options(), diampb.E_Def).(*diampb.AVPDef)
			if def == nil {
				continue
			}
			name := string(v.Desc.Name())
			d.byName[name] = append(d.byName[name], avpDef{
				name: name, code: uint32(v.Desc.Number()), vendor: def.GetVendor(),
				m: def.GetM(), typ: def.GetType(), file: f.Desc.Path(),
			})
		}
	}
}

// lookup resolves a field to its dictionary entry: same-file entry first, then
// a unique entry anywhere in the request.
func (d *dict) lookup(fld *protogen.Field, file string) (avpDef, error) {
	name := proto.GetExtension(fld.Desc.Options(), diampb.E_Avp).(string)
	if name == "" {
		name = strings.ToUpper(string(fld.Desc.Name()))
	}
	cands := d.byName[name]
	for _, c := range cands {
		if c.file == file {
			return c, nil
		}
	}
	switch len(cands) {
	case 0:
		return avpDef{}, fmt.Errorf("field %s: no dictionary entry %s", fld.Desc.FullName(), name)
	case 1:
		return cands[0], nil
	}
	return avpDef{}, fmt.Errorf("field %s: dictionary entry %s is ambiguous; set (diam.avp)", fld.Desc.FullName(), name)
}

// ---------------------------------------------------------------------------

type card int

const (
	required card = iota
	optional
	repeated
)

type field struct {
	f      *protogen.Field
	def    avpDef
	card   card
	min    int
	max    int // 0 = unbounded
	goType string
	reqBit int // bit index in seen mask for required fields
}

func generateFile(gen *protogen.Plugin, d *dict, f *protogen.File) error {
	g := gen.NewGeneratedFile(f.GeneratedFilenamePrefix+".diam.go", f.GoImportPath)
	g.P("// Code generated by protoc-gen-go-diam. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()

	for _, e := range f.Enums {
		if proto.GetExtension(e.Desc.Options(), diampb.E_Dictionary).(bool) {
			genDictConsts(g, e)
			continue
		}
		genEnum(g, e)
	}
	var cmds []*protogen.Message
	for _, m := range f.Messages {
		fields, err := buildFields(g, d, f, m)
		if err != nil {
			return err
		}
		cmd, _ := proto.GetExtension(m.Desc.Options(), diampb.E_Command).(*diampb.Command)
		genStruct(g, m, fields)
		genAppendAVPs(g, m, fields)
		genDecodeAVPs(g, m, fields)
		genValidate(g, m, fields)
		if cmd != nil {
			genCommand(g, m, cmd)
			cmds = append(cmds, m)
		}
	}
	if len(cmds) > 0 {
		g.P("func init() {")
		for _, m := range cmds {
			cmd := proto.GetExtension(m.Desc.Options(), diampb.E_Command).(*diampb.Command)
			g.P(g.QualifiedGoIdent(diamPkg.Ident("Register")), "(", cmd.GetAppId(), ", ", cmd.GetCode(), ", ", cmd.GetRequest(),
				", func() ", g.QualifiedGoIdent(diamPkg.Ident("Message")), " { return new(", m.GoIdent.GoName, ") })")
		}
		g.P("}")
	}
	return nil
}

func genDictConsts(g *protogen.GeneratedFile, e *protogen.Enum) {
	g.P("// AVP codes defined by this file.")
	g.P("const (")
	for _, v := range e.Values {
		if v.Desc.Number() == 0 {
			continue
		}
		g.P("AVP", camel(string(v.Desc.Name())), " uint32 = ", v.Desc.Number())
	}
	g.P(")")
	g.P()
}

func genEnum(g *protogen.GeneratedFile, e *protogen.Enum) {
	name := e.GoIdent.GoName
	prefix := strings.ToUpper(snake(name)) + "_"
	g.P("type ", name, " int32")
	g.P()
	g.P("const (")
	var names []string
	for _, v := range e.Values {
		vn := string(v.Desc.Name())
		if v.Desc.Number() == 0 && strings.HasSuffix(vn, "_UNSPECIFIED") {
			continue
		}
		cn := name + camel(strings.TrimPrefix(vn, prefix))
		names = append(names, fmt.Sprintf("case %s: return %q", cn, strings.TrimPrefix(vn, prefix)))
		g.P(cn, " ", name, " = ", v.Desc.Number())
	}
	g.P(")")
	g.P()
	g.P("func (v ", name, ") String() string {")
	g.P("switch v {")
	for _, n := range names {
		g.P(n)
	}
	g.P("}")
	g.P("return ", g.QualifiedGoIdent(protogen.GoImportPath("strconv").Ident("Itoa")), "(int(v))")
	g.P("}")
	g.P()
}

func buildFields(g *protogen.GeneratedFile, d *dict, f *protogen.File, m *protogen.Message) ([]field, error) {
	var out []field
	reqBit := 0
	for _, fl := range m.Fields {
		def, err := d.lookup(fl, f.Desc.Path())
		if err != nil {
			return nil, err
		}
		fd := field{f: fl, def: def, reqBit: -1}
		switch {
		case fl.Desc.IsList():
			fd.card = repeated
			fd.min = int(proto.GetExtension(fl.Desc.Options(), diampb.E_Min).(uint32))
			fd.max = int(proto.GetExtension(fl.Desc.Options(), diampb.E_Max).(uint32))
		case fl.Desc.HasPresence() && (fl.Desc.HasOptionalKeyword() || fl.Desc.ContainingOneof() != nil):
			fd.card = optional
		case fl.Desc.Kind() == protoreflect.MessageKind:
			// proto3 message fields always have presence; without `optional`
			// we treat them as required.
			fd.card = required
		default:
			fd.card = required
		}
		if fd.card == required {
			fd.reqBit = reqBit
			reqBit++
			if reqBit > 64 {
				return nil, fmt.Errorf("%s: more than 64 required AVPs", m.Desc.FullName())
			}
		}
		gt, err := goType(g, fl, def)
		if err != nil {
			return nil, err
		}
		fd.goType = gt
		out = append(out, fd)
	}
	return out, nil
}

func goType(g *protogen.GeneratedFile, fl *protogen.Field, def avpDef) (string, error) {
	k := fl.Desc.Kind()
	bad := func() (string, error) {
		return "", fmt.Errorf("field %s: proto kind %s does not fit AVP type %s", fl.Desc.FullName(), k, def.typ)
	}
	switch def.typ {
	case diampb.Type_UTF8_STRING, diampb.Type_DIAMETER_IDENTITY, diampb.Type_DIAMETER_URI:
		if k != protoreflect.StringKind {
			return bad()
		}
		return "string", nil
	case diampb.Type_OCTET_STRING:
		if k == protoreflect.StringKind {
			return "string", nil
		}
		if k != protoreflect.BytesKind {
			return bad()
		}
		return "[]byte", nil
	case diampb.Type_ADDRESS:
		if k != protoreflect.BytesKind {
			return bad()
		}
		return g.QualifiedGoIdent(netipPkg.Ident("Addr")), nil
	case diampb.Type_TIME:
		if k != protoreflect.Uint32Kind {
			return bad()
		}
		return g.QualifiedGoIdent(timePkg.Ident("Time")), nil
	case diampb.Type_UNSIGNED32:
		if k != protoreflect.Uint32Kind {
			return bad()
		}
		return "uint32", nil
	case diampb.Type_UNSIGNED64:
		if k != protoreflect.Uint64Kind {
			return bad()
		}
		return "uint64", nil
	case diampb.Type_INTEGER32:
		if k != protoreflect.Int32Kind {
			return bad()
		}
		return "int32", nil
	case diampb.Type_INTEGER64:
		if k != protoreflect.Int64Kind {
			return bad()
		}
		return "int64", nil
	case diampb.Type_FLOAT32:
		if k != protoreflect.FloatKind {
			return bad()
		}
		return "float32", nil
	case diampb.Type_FLOAT64:
		if k != protoreflect.DoubleKind {
			return bad()
		}
		return "float64", nil
	case diampb.Type_ENUMERATED:
		switch k {
		case protoreflect.EnumKind:
			return g.QualifiedGoIdent(fl.Enum.GoIdent), nil
		case protoreflect.Int32Kind:
			return "int32", nil
		}
		return bad()
	case diampb.Type_GROUPED:
		if k != protoreflect.MessageKind {
			return bad()
		}
		return g.QualifiedGoIdent(fl.Message.GoIdent), nil
	}
	return bad()
}

func fullType(g *protogen.GeneratedFile, fd field) string {
	switch fd.card {
	case optional:
		if fd.def.typ == diampb.Type_GROUPED {
			return "*" + fd.goType
		}
		return diamIdent(g, "Opt") + "[" + fd.goType + "]"
	case repeated:
		return "[]" + fd.goType
	}
	return fd.goType
}

func genStruct(g *protogen.GeneratedFile, m *protogen.Message, fields []field) {
	cmd, _ := proto.GetExtension(m.Desc.Options(), diampb.E_Command).(*diampb.Command)
	g.P(m.Comments.Leading, "type ", m.GoIdent.GoName, " struct {")
	if cmd != nil {
		g.P("Header ", g.QualifiedGoIdent(diamPkg.Ident("Header")))
		g.P()
	}
	for _, fd := range fields {
		t := fullType(g, fd)
		mark := map[card]string{required: "{ }", optional: "[ ]", repeated: "*[ ]"}[fd.card]
		g.P(fd.f.GoName, " ", t, " // ", mark, " ", avpLabel(fd.def))
	}
	g.P()
	g.P("// Unknown holds AVPs not described above, re-encoded verbatim by Marshal.")
	g.P("Unknown []", g.QualifiedGoIdent(diamPkg.Ident("RawAVP")))
	g.P()
	g.P("seen   uint64 // required AVPs seen by Unmarshal")
	g.P("excess []", g.QualifiedGoIdent(diamPkg.Ident("RawAVP")), " // occurrences beyond the grammar maximum")
	g.P("decoded bool")
	g.P("}")
	g.P()
}

func avpLabel(d avpDef) string {
	s := fmt.Sprintf("%s code %d", d.name, d.code)
	if d.vendor != 0 {
		s += fmt.Sprintf(" vendor %d", d.vendor)
	}
	return s
}

func diamIdent(g *protogen.GeneratedFile, name string) string {
	return g.QualifiedGoIdent(diamPkg.Ident(name))
}

func appendScalar(g *protogen.GeneratedFile, fd field, v string) {
	d := fd.def
	flags := "0"
	if d.m {
		flags = diamIdent(g, "AVPFlagMandatory")
	}
	if d.typ == diampb.Type_GROUPED {
		g.P("b, s = ", diamIdent(g, "BeginAVP"), "(b, ", d.code, ", ", flags, ", ", d.vendor, ")")
		g.P("b = ", v, ".AppendAVPs(b)")
		g.P("b = ", diamIdent(g, "EndAVP"), "(b, s)")
		return
	}
	g.P("b, s = ", diamIdent(g, "BeginAVP"), "(b, ", d.code, ", ", flags, ", ", d.vendor, ")")
	switch d.typ {
	case diampb.Type_UTF8_STRING, diampb.Type_DIAMETER_IDENTITY, diampb.Type_DIAMETER_URI, diampb.Type_OCTET_STRING:
		g.P("b = append(b, ", v, "...)")
	case diampb.Type_ADDRESS:
		g.P("b = ", diamIdent(g, "AppendAddress"), "(b, ", v, ")")
	case diampb.Type_TIME:
		g.P("b = ", diamIdent(g, "AppendTime"), "(b, ", v, ")")
	case diampb.Type_UNSIGNED32:
		g.P("b = ", diamIdent(g, "AppendUnsigned32"), "(b, ", v, ")")
	case diampb.Type_UNSIGNED64:
		g.P("b = ", diamIdent(g, "AppendUnsigned64"), "(b, ", v, ")")
	case diampb.Type_INTEGER32:
		g.P("b = ", diamIdent(g, "AppendInteger32"), "(b, ", v, ")")
	case diampb.Type_INTEGER64:
		g.P("b = ", diamIdent(g, "AppendInteger64"), "(b, ", v, ")")
	case diampb.Type_FLOAT32:
		g.P("b = ", diamIdent(g, "AppendFloat32"), "(b, ", v, ")")
	case diampb.Type_FLOAT64:
		g.P("b = ", diamIdent(g, "AppendFloat64"), "(b, ", v, ")")
	case diampb.Type_ENUMERATED:
		g.P("b = ", diamIdent(g, "AppendInteger32"), "(b, int32(", v, "))")
	}
	g.P("b = ", diamIdent(g, "EndAVP"), "(b, s)")
}

func genAppendAVPs(g *protogen.GeneratedFile, m *protogen.Message, fields []field) {
	name := m.GoIdent.GoName
	g.P("// AppendAVPs appends the AVPs of m in grammar order.")
	g.P("func (m *", name, ") AppendAVPs(b []byte) []byte {")
	g.P("var s int")
	g.P("_ = s")
	// Fixed-position AVPs first, then the rest in field order.
	ordered := append([]field(nil), fields...)
	sort.SliceStable(ordered, func(i, j int) bool {
		return isFixed(ordered[i]) && !isFixed(ordered[j])
	})
	for _, fd := range ordered {
		v := "m." + fd.f.GoName
		switch fd.card {
		case required:
			if fd.def.typ == diampb.Type_GROUPED {
				appendScalar(g, fd, "(&"+v+")")
			} else {
				appendScalar(g, fd, v)
			}
		case optional:
			if fd.def.typ == diampb.Type_GROUPED {
				g.P("if ", v, " != nil {")
				appendScalar(g, fd, v)
			} else {
				g.P("if ", v, ".Set {")
				appendScalar(g, fd, v+".V")
			}
			g.P("}")
		case repeated:
			g.P("for i := range ", v, " {")
			if fd.def.typ == diampb.Type_GROUPED {
				appendScalar(g, fd, "(&"+v+"[i])")
			} else {
				appendScalar(g, fd, v+"[i]")
			}
			g.P("}")
		}
	}
	g.P("for _, a := range m.Unknown {")
	g.P("b = ", diamIdent(g, "AppendRaw"), "(b, a)")
	g.P("}")
	g.P("return b")
	g.P("}")
	g.P()
}

func isFixed(fd field) bool {
	return proto.GetExtension(fd.f.Desc.Options(), diampb.E_Fixed).(bool)
}

func decodeFunc(d avpDef) string {
	switch d.typ {
	case diampb.Type_UTF8_STRING, diampb.Type_DIAMETER_IDENTITY, diampb.Type_DIAMETER_URI:
		return "String"
	case diampb.Type_OCTET_STRING:
		return "Bytes"
	case diampb.Type_ADDRESS:
		return "Address"
	case diampb.Type_TIME:
		return "Time"
	case diampb.Type_UNSIGNED32:
		return "Unsigned32"
	case diampb.Type_UNSIGNED64:
		return "Unsigned64"
	case diampb.Type_INTEGER32, diampb.Type_ENUMERATED:
		return "Integer32"
	case diampb.Type_INTEGER64:
		return "Integer64"
	case diampb.Type_FLOAT32:
		return "Float32"
	case diampb.Type_FLOAT64:
		return "Float64"
	}
	return ""
}

func genDecodeAVPs(g *protogen.GeneratedFile, m *protogen.Message, fields []field) {
	name := m.GoIdent.GoName
	g.P("// DecodeAVPs fills m from an AVP sequence. Unknown AVPs go to m.Unknown;")
	g.P("// repeats of single-occurrence AVPs are kept for Validate to report.")
	g.P("func (m *", name, ") DecodeAVPs(data []byte) error {")
	g.P("m.decoded = true")
	g.P("for len(data) > 0 {")
	g.P("a, rest, err := ", diamIdent(g, "NextAVP"), "(data)")
	g.P("if err != nil { return err }")
	g.P("data = rest")
	g.P("switch uint64(a.Vendor)<<32 | uint64(a.Code) {")
	for _, fd := range fields {
		d := fd.def
		g.P("case ", uint64(d.vendor)<<32|uint64(d.code), ": // ", d.name)
		target := "m." + fd.f.GoName
		var val string
		if d.typ == diampb.Type_GROUPED {
			g.P("var v ", fd.goType)
			g.P("if err := v.DecodeAVPs(a.Data); err != nil { return err }")
			val = "v"
		} else {
			g.P("x, err := ", diamIdent(g, decodeFunc(d)), "(a)")
			g.P("if err != nil { return err }")
			val = "x"
			if d.typ == diampb.Type_ENUMERATED {
				val = fd.goType + "(x)"
			}
			if d.typ == diampb.Type_OCTET_STRING && fd.goType == "string" {
				g.P("_ = x")
				val = "string(a.Data)"
			}
		}
		switch fd.card {
		case required:
			bit := fmt.Sprintf("uint64(1)<<%d", fd.reqBit)
			g.P("if m.seen&(", bit, ") != 0 { m.excess = append(m.excess, ", diamIdent(g, "Clone"), "(a)); continue }")
			g.P("m.seen |= ", bit)
			g.P(target, " = ", val)
		case optional:
			present := target + ".Set"
			if d.typ == diampb.Type_GROUPED {
				present = target + " != nil"
			}
			g.P("if ", present, " { m.excess = append(m.excess, ", diamIdent(g, "Clone"), "(a)); continue }")
			if d.typ == diampb.Type_GROUPED {
				g.P(target, " = &", val)
			} else {
				g.P(target, " = ", diamIdent(g, "Some"), "(", val, ")")
			}
		case repeated:
			if fd.max > 0 {
				g.P("if len(", target, ") >= ", fd.max, " { m.excess = append(m.excess, ", diamIdent(g, "Clone"), "(a)); continue }")
			}
			g.P(target, " = append(", target, ", ", val, ")")
		}
	}
	g.P("default:")
	g.P("m.Unknown = append(m.Unknown, ", diamIdent(g, "Clone"), "(a))")
	g.P("}")
	g.P("}")
	g.P("return nil")
	g.P("}")
	g.P()
}

func genValidate(g *protogen.GeneratedFile, m *protogen.Message, fields []field) {
	name := m.GoIdent.GoName
	g.P("// Validate checks the grammar: required AVPs (for decoded messages),")
	g.P("// occurrence bounds, unknown mandatory AVPs, and nested groups.")
	g.P("func (m *", name, ") Validate() error {")
	g.P("if len(m.excess) > 0 { return ", diamIdent(g, "TooMany"), "(m.excess[0], \"\") }")
	for _, fd := range fields {
		d := fd.def
		v := "m." + fd.f.GoName
		switch fd.card {
		case required:
			g.P("if m.decoded && m.seen&(uint64(1)<<", fd.reqBit, ") == 0 { return ", diamIdent(g, "Missing"), "(", d.code, ", ", d.vendor, ", ", fmt.Sprintf("%q", d.name), ") }")
			if d.typ == diampb.Type_GROUPED {
				g.P("if err := ", v, ".Validate(); err != nil { return err }")
			}
		case optional:
			if d.typ == diampb.Type_GROUPED {
				g.P("if ", v, " != nil { if err := ", v, ".Validate(); err != nil { return err } }")
			}
		case repeated:
			if fd.min > 0 {
				g.P("if len(", v, ") < ", fd.min, " { return ", diamIdent(g, "TooFew"), "(", d.code, ", ", d.vendor, ", ", fmt.Sprintf("%q", d.name), ", ", fd.min, ") }")
			}
			if d.typ == diampb.Type_GROUPED {
				g.P("for i := range ", v, " { if err := ", v, "[i].Validate(); err != nil { return err } }")
			}
		}
	}
	g.P("return ", diamIdent(g, "CheckUnknown"), "(m.Unknown)")
	g.P("}")
	g.P()
}

func genCommand(g *protogen.GeneratedFile, m *protogen.Message, cmd *diampb.Command) {
	name := m.GoIdent.GoName
	flags := "0"
	var fl []string
	if cmd.GetRequest() {
		fl = append(fl, diamIdent(g, "FlagRequest"))
	}
	if cmd.GetProxiable() {
		fl = append(fl, diamIdent(g, "FlagProxiable"))
	}
	if len(fl) > 0 {
		flags = strings.Join(fl, "|")
	}
	g.P("// DiamHeader implements diam.Message.")
	g.P("func (m *", name, ") DiamHeader() *", diamIdent(g, "Header"), " { return &m.Header }")
	g.P()
	g.P("// AppendMarshal appends the encoded message. Command code and application id")
	g.P("// are set from the grammar; R and P bits are forced to the grammar's values.")
	g.P("func (m *", name, ") AppendMarshal(b []byte) ([]byte, error) {")
	g.P("h := m.Header")
	g.P("h.CommandCode, h.AppID = ", cmd.GetCode(), ", ", cmd.GetAppId())
	g.P("h.Flags = h.Flags&^(", diamIdent(g, "FlagRequest"), "|", diamIdent(g, "FlagProxiable"), ") | ", flags)
	g.P("start := len(b)")
	g.P("b = ", diamIdent(g, "AppendHeader"), "(b, &h)")
	g.P("b = m.AppendAVPs(b)")
	g.P("return ", diamIdent(g, "FinishMessage"), "(b, start)")
	g.P("}")
	g.P()
	g.P("// Marshal encodes the message.")
	g.P("func (m *", name, ") Marshal() ([]byte, error) { return m.AppendMarshal(nil) }")
	g.P()
	g.P("// Unmarshal decodes a whole message. It fails only on framing errors;")
	g.P("// grammar violations are reported by Validate.")
	g.P("func (m *", name, ") Unmarshal(b []byte) error {")
	g.P("h, avps, err := ", diamIdent(g, "ParseHeader"), "(b)")
	g.P("if err != nil { return err }")
	g.P("*m = ", name, "{Header: h}")
	g.P("return m.DecodeAVPs(avps)")
	g.P("}")
	g.P()
}

// camel turns SCREAMING_SNAKE into CamelCase.
func camel(s string) string {
	parts := strings.Split(strings.ToLower(s), "_")
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

// snake turns CamelCase into snake_case.
func snake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if r >= 'A' && r <= 'Z' {
			if i > 0 {
				b.WriteByte('_')
			}
			r += 'a' - 'A'
		}
		b.WriteRune(r)
	}
	return b.String()
}
